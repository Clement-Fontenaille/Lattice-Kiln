<#
.SYNOPSIS
  M0 - aggregate results/runs/*.json into results/summary.md.

.DESCRIPTION
  Reads every run record, computes median / min-max per
  (runtime, model, quant, context_fill) cell, flags "comfortable" against the
  PROTOCOL.md thresholds, and lists skipped / OOM / error cells.

.NOTES
  Windows PowerShell 5.1 compatible. ASCII only. Regenerates summary.md; do not
  hand-edit that file.
#>

[CmdletBinding()]
param(
  [string] $ResultsDir = (Join-Path $PSScriptRoot '..\results'),
  [double] $GenFloor   = 15,
  [double] $TtftCeilMs = 2000,
  [double] $SwitchCeilMs = 5000
)

$ErrorActionPreference = 'Stop'
$runsDir = Join-Path $ResultsDir 'runs'
$outFile = Join-Path $ResultsDir 'summary.md'
if (-not (Test-Path $runsDir)) { throw "no results at $runsDir" }

$records = Get-ChildItem $runsDir -Filter '*.json' | ForEach-Object {
  try { Get-Content $_.FullName -Raw | ConvertFrom-Json } catch { Write-Warning "bad json: $($_.Name)" }
}

function Median([double[]] $v) {
  if (-not $v -or $v.Count -eq 0) { return $null }
  $s = $v | Sort-Object
  $n = $s.Count
  if ($n % 2) { return [double]$s[[int](($n - 1) / 2)] }
  return [math]::Round((($s[$n/2 - 1] + $s[$n/2]) / 2), 2)
}

$runs   = $records | Where-Object { $_.schema -eq 'm0-run/1' }
$switch = $records | Where-Object { $_.schema -eq 'm0-switch/1' }

$cold = @{}
foreach ($r in ($runs | Where-Object { $_.note -eq 'cold-load probe' -and $_.status -eq 'ok' })) {
  $cold["$($r.runtime)|$($r.model)|$($r.quant)"] = $r.metrics.load_ms
}

$good = $runs | Where-Object { $_.status -eq 'ok' -and -not $_.warmup -and $_.note -ne 'cold-load probe' }
$bad  = $runs | Where-Object { $_.status -in @('skipped','oom','error') }

$hostInfo = $null
$hostFile = Join-Path $ResultsDir 'host.json'
if (Test-Path $hostFile) { $hostInfo = Get-Content $hostFile -Raw | ConvertFrom-Json }

$md = New-Object System.Text.StringBuilder
function W([string] $s) { [void]$md.AppendLine($s) }

W "# M0 Results Summary"
W ""
W "_Generated by aggregate.ps1. Do not hand-edit._"
W ""
if ($hostInfo) {
  $g = $hostInfo.gpus[0]
  W ("Host: {0}, {1} GB VRAM | {2} | {3} GB RAM | {4}" -f `
     $g.name, ([math]::Round($g.vram_mb/1024,1)), $hostInfo.cpu.name.Trim(), $hostInfo.ram_gb, $hostInfo.os.caption)
}
W ("Thresholds: gen >= {0} tok/s, prompt-eval <= {1} ms, switch <= {2} ms" -f $GenFloor, $TtftCeilMs, $SwitchCeilMs)
W ""

$byModel = $good | Group-Object runtime, model, quant | Sort-Object Name
$lastModelKey = $null
foreach ($grp in $byModel) {
  $runtime, $model, $quant = $grp.Group[0].runtime, $grp.Group[0].model, $grp.Group[0].quant
  $mk = "$runtime | $model"
  if ($mk -ne $lastModelKey) {
    W "## $mk"
    W ""
    $lastModelKey = $mk
  }
  $cl = $cold["$runtime|$model|$quant"]
  W ("### $quant" + $(if ($cl) { "  (cold load {0} ms)" -f $cl } else { "" }))
  W ""
  W "| fill | prefill tok/s (med / min-max) | gen tok/s (med / min-max) | prompt-eval ms (med) | vram MB | offload | ok? |"
  W "|---:|---|---|---:|---:|:---:|:---:|"
  foreach ($fillGrp in ($grp.Group | Group-Object context_fill | Sort-Object { [int]$_.Name })) {
    $cells = $fillGrp.Group
    $pf = $cells | ForEach-Object { $_.metrics.prefill_tok_s } | Where-Object { $_ -ne $null }
    $gn = $cells | ForEach-Object { $_.metrics.gen_tok_s } | Where-Object { $_ -ne $null }
    $pe = $cells | ForEach-Object { $_.metrics.prompt_eval_ms } | Where-Object { $_ -ne $null }
    $vr = ($cells | ForEach-Object { $_.metrics.vram_resident_mb } | Where-Object { $_ -ne $null } | Select-Object -First 1)
    $gl = ($cells | ForEach-Object { if ($_.metrics.gpu_layers -ne $null) { "$($_.metrics.gpu_layers)/$($_.metrics.total_layers)" } } | Select-Object -First 1)
    $pfMed = Median ([double[]]$pf); $gnMed = Median ([double[]]$gn); $peMed = Median ([double[]]$pe)
    $ok = if ($gnMed -ne $null -and $gnMed -ge $GenFloor -and ($peMed -eq $null -or $peMed -le $TtftCeilMs)) { "yes" } else { "no" }
    $pfStr = if ($pf) { "{0} / {1}-{2}" -f $pfMed, ([math]::Round(($pf | Measure-Object -Min).Minimum,1)), ([math]::Round(($pf | Measure-Object -Max).Maximum,1)) } else { "-" }
    $gnStr = if ($gn) { "{0} / {1}-{2}" -f $gnMed, ([math]::Round(($gn | Measure-Object -Min).Minimum,1)), ([math]::Round(($gn | Measure-Object -Max).Maximum,1)) } else { "-" }
    W ("| {0} | {1} | {2} | {3} | {4} | {5} | {6} |" -f $fillGrp.Name, $pfStr, $gnStr, $(if($peMed){$peMed}else{'-'}), $(if($vr){$vr}else{'-'}), $(if($gl){$gl}else{'-'}), $ok)
  }
  W ""
}

if ($switch) {
  W "## Model switch cost"
  W ""
  W "| from | to | unload ms | load ms | switch ms | ok? |"
  W "|---|---|---:|---:|---:|:---:|"
  foreach ($s in ($switch | Sort-Object timestamp)) {
    $ok = if ($s.switch_ms -le $SwitchCeilMs) { "yes" } else { "no" }
    W ("| {0} | {1} | {2} | {3} | {4} | {5} |" -f $s.from, $s.to, $s.unload_ms, $s.load_ms, $s.switch_ms, $ok)
  }
  W ""
}

$concurrent = $records | Where-Object { $_.schema -eq 'm0-concurrent/1' -and $_.status -eq 'ok' }
if ($concurrent) {
  W "## Concurrent load (inference vs. dev environment)"
  W ""
  W "_Host load is a synthetic proxy: N CPU workers + RAM churn standing in for editor + language server + build._"
  W ""
  W "| model | quant | fill | condition | gen tok/s (med / min-max) | prefill tok/s (med) | n |"
  W "|---|---|---:|---|---|---:|---:|"
  $cRows = @{}
  foreach ($grp in ($concurrent | Group-Object model, quant, context_fill, condition)) {
    $g0 = $grp.Group[0]
    $gn = $grp.Group | ForEach-Object { $_.metrics.gen_tok_s } | Where-Object { $_ -ne $null }
    $pf = $grp.Group | ForEach-Object { $_.metrics.prefill_tok_s } | Where-Object { $_ -ne $null }
    $gnMed = Median ([double[]]$gn); $pfMed = Median ([double[]]$pf)
    $cRows["$($g0.model)|$($g0.quant)|$($g0.context_fill)|$($g0.condition)"] = $gnMed
    $gnStr = if ($gn) { "{0} / {1}-{2}" -f $gnMed, ([math]::Round(($gn|Measure-Object -Min).Minimum,1)), ([math]::Round(($gn|Measure-Object -Max).Maximum,1)) } else { "-" }
    W ("| {0} | {1} | {2} | {3} | {4} | {5} | {6} |" -f $g0.model, $g0.quant, $g0.context_fill, $g0.condition, $gnStr, $(if($pfMed){$pfMed}else{'-'}), $grp.Count)
  }
  W ""
  foreach ($k in ($cRows.Keys | Where-Object { $_ -like '*|idle' })) {
    $ck = $k -replace '\|idle$', '|concurrent'
    if ($cRows.ContainsKey($ck) -and $cRows[$k]) {
      $delta = [math]::Round((($cRows[$ck] - $cRows[$k]) / $cRows[$k]) * 100, 1)
      W ("- **{0}**: idle {1} -> concurrent {2} tok/s  (**{3}%**)" -f ($k -replace '\|idle$',''), $cRows[$k], $cRows[$ck], $delta)
    }
  }
  W ""
}

$drift = $records | Where-Object { $_.schema -eq 'm0-drift/1' -and $_.status -eq 'ok' }
if ($drift) {
  W "## Sustained drift (continuous generation)"
  W ""
  foreach ($grp in ($drift | Group-Object model, quant)) {
    $g0 = $grp.Group[0]
    $maxT = ($grp.Group | Measure-Object elapsed_s -Maximum).Maximum
    $first = $grp.Group | Where-Object { $_.elapsed_s -le 60 } | ForEach-Object { $_.metrics.gen_tok_s } | Where-Object { $_ -ne $null }
    $last  = $grp.Group | Where-Object { $_.elapsed_s -ge ($maxT - 60) } | ForEach-Object { $_.metrics.gen_tok_s } | Where-Object { $_ -ne $null }
    $fMed = Median ([double[]]$first); $lMed = Median ([double[]]$last)
    $drop = if ($fMed) { [math]::Round((($lMed - $fMed) / $fMed) * 100, 1) } else { $null }
    W ("- **{0} {1}**: {2} iterations over {3}s. First-minute median {4} tok/s, last-minute median {5} tok/s  (**{6}%**)." -f `
       $g0.model, $g0.quant, $grp.Count, $maxT, $fMed, $lMed, $drop)
  }
  W ""
}

if ($bad) {
  W "## Skipped / OOM / error"
  W ""
  W "| runtime | model | quant | fill | status | note |"
  W "|---|---|---|---:|:---:|---|"
  foreach ($b in ($bad | Sort-Object runtime, model, quant, context_fill | Select-Object -Unique runtime, model, quant, context_fill, status, note)) {
    $note = ("{0}" -f $b.note); if ($note.Length -gt 80) { $note = $note.Substring(0,77) + '...' }
    W ("| {0} | {1} | {2} | {3} | {4} | {5} |" -f $b.runtime, $b.model, $b.quant, $b.context_fill, $b.status, $note)
  }
  W ""
}

Set-Content -Path $outFile -Value $md.ToString() -Encoding utf8
Write-Host "wrote $outFile"
Write-Host ("cells: {0} ok, {1} not-ok, {2} switch" -f $good.Count, $bad.Count, ($switch | Measure-Object).Count)
